-- 실행 시점: 1회성. 이미 적용되었다면 같은 값으로 재실행해도 멱등(idempotent)하게 같은 결과가 되므로
--           안전하게 다시 돌려도 문제는 없으나, 보통 한 번만 실행하면 충분함.
-- ─────────────────────────────────────────────────────────────────
UPDATE users SET tax_categories = '["법인세"]' WHERE email = 'test@taxist.kr';
