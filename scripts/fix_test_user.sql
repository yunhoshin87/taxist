-- 목적: 테스트/시드 데이터가 비어있거나 잘못된 상태였던 테스트 사용자에게 기능 검증(법인세 카테고리
--       필터링 등)이 가능하도록 임의의 유효 값을 채워주기 위한 핫픽스. 운영 사용자 데이터에는 영향 없음
--       (WHERE email = 'test@taxist.kr'로 단일 테스트 계정만 한정).
